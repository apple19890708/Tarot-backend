// 四種問法。others 會提到具體的人，用來觸發宮廷牌的人物判定。
const FRAMES = [
  (topic) => `${topic}接下來會怎麼走`,
  (topic) => `該不該繼續${topic}`,
  (topic) => `${topic}要怎麼處理比較好`,
  (topic) => `主管和同事對${topic}的看法是什麼`,
]

// others 那一式在不同領域要換成合適的對象
const OTHERS_BY_DOMAIN = {
  work: (topic) => `主管和同事對${topic}的看法是什麼`,
  money: (topic) => `家人對${topic}的態度會不會影響我`,
  love: (topic) => `對方現在對${topic}是怎麼想的`,
  social: (topic) => `朋友們對${topic}的反應會是什麼`,
  study: (topic) => `老師和同學對${topic}怎麼看`,
}

function buildQuestions(domain) {
  const topics = TOPICS[domain]
  const questions = []

  topics.forEach((topic) => {
    questions.push(FRAMES[0](topic))
    questions.push(FRAMES[1](topic))
    questions.push(FRAMES[2](topic))
    questions.push(OTHERS_BY_DOMAIN[domain](topic))
  })

  return questions
}

module.exports = { TOPICS, buildQuestions }
