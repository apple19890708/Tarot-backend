const CONN = { GG: ['而', '加上', '同時', '剛好'], BG: ['好在', '幸好', '還好', '至少'], GB: ['可是', '偏偏', '只是', '但'], BB: ['再加上', '而且', '同時', '偏偏'] }
const CUPS = Object.keys(CUP)
// [正位好不好, 逆位好不好]：聖杯四、五、七是正位壞、逆位好；聖杯八正逆都算不好（走或走不了）
const CUP_GOOD = (c) => ({ 聖杯四: [false, true], 聖杯五: [false, true], 聖杯七: [false, true], 聖杯八: [false, false] }[c] || [true, false])
// 塔的逆位說法（拖延面對、問題壓著還沒爆）在感情裡也不是好事，正逆都算壞
const MAJ_GOOD = (m) => ({ 惡魔: [false, true], 月亮: [false, true], 塔: [false, false] }[m] || [true, false])

// 大→小：段序 s＝大牌、列序 i＝聖杯；slot 0＝大正杯正、1＝大正杯逆、2＝大逆杯正、3＝大逆杯逆
function heads(major) {
  const s = MAJORS.indexOf(major)
  const [mu, mr] = MAJ[major]
  const mg = MAJ_GOOD(major)
  return CUPS.map((c, i) => {
    const [cu, cr] = CUP[c]
    const op = [cu[(i + s) % 8], cr[(i + s) % 8], cu[(i + s + 4) % 8], cr[(i + s + 4) % 8]]
    const sc = [mu[i % 8], mu[(i + 5) % 8], mr[(i + 2) % 8], mr[(i + 7) % 8]]
    const cg = CUP_GOOD(c)
    const first = [cg[0], cg[1], cg[0], cg[1]]
    const second = [mg[0], mg[0], mg[1], mg[1]]
    return [c, op.map((o, k) => {
      const key = (first[k] ? 'G' : 'B') + (second[k] ? 'G' : 'B')
      // 大牌子句本身含連接詞、或頭尾疊字時換下一個（「剛好時機剛好」「幸好好運」）
      const clash = (x) => sc[k].includes(x) || x.slice(-1) === sc[k][0]
      let c = CONN[key][(i + s + k) % 4]
      for (let d = 1; d < 4 && clash(c); d += 1) c = CONN[key][(i + s + k + d) % 4]
      return `${o}，${c}${sc[k]}。`
    })]
  })
}
