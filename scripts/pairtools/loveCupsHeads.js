// 小→大：段序 s＝聖杯、列序 i＝大牌；slot 0＝杯正大正、1＝杯正大逆、2＝杯逆大正、3＝杯逆大逆
function headsSmall(cup) {
  const s = CUPS.indexOf(cup)
  const [cu, cr] = CUP2[cup]
  const cg = CUP_GOOD(cup)
  return MAJORS.map((m, i) => {
    const [mu, mr] = MAJ2[m]
    const op = [mu[(i + s) % 8], mr[(i + s) % 8], mu[(i + s + 4) % 8], mr[(i + s + 4) % 8]]
    const sc = [cu[i % 8], cu[(i + 5) % 8], cr[(i + 2) % 8], cr[(i + 7) % 8]]
    const mg = MAJ_GOOD(m)
    const first = [mg[0], mg[1], mg[0], mg[1]]
    const second = [cg[0], cg[0], cg[1], cg[1]]
    return [m, op.map((o, k) => {
      const key = (first[k] ? 'G' : 'B') + (second[k] ? 'G' : 'B')
      const clash = (x) => sc[k].includes(x) || x.slice(-1) === sc[k][0]
      let c = CONN[key][(i + s + k) % 4]
      for (let d = 1; d < 4 && clash(c); d += 1) c = CONN[key][(i + s + k + d) % 4]
      return `${o}，${c}${sc[k]}。`
    })]
  })
}
