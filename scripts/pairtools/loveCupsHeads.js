    const fs = require('fs')
    // tails 檔有 major 就是大→小，有 cup 就是小→大
    const { major, cup, tails } = JSON.parse(fs.readFileSync(args[1], 'utf8'))
    const src = major || cup
    const rows = (major ? heads(major) : headsSmall(cup)).map(([to, hs]) => {
      const t = tails[to]
      if (!t || t.length !== 4) throw new Error('缺 ' + to + ' 的後半段')
      return [src, to, hs.map((h, k) => h + t[k])]
    })
    fs.writeFileSync(args[2], JSON.stringify({ domain: 'love', suit: 'cups', rows }), 'utf8')
