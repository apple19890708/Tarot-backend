// 依 §14.12 的輪轉公式組出每一句的開頭（大牌）與第二子句（寶劍）
function heads(sword) {
  const s = SUITS.indexOf(sword)
  return MAJORS.map((m, i) => {
    const [mu, mr] = MAJ[m]
    const [su, sr] = SW[sword]
    const alt = ALT[sword] && ALT[sword][m]
    const op = alt
      ? [alt[0][0], alt[1][0], alt[0][1], alt[1][1]]
      : [mu[(i + s) % 8], mr[(i + s) % 8], mu[(i + s + 4) % 8], mr[(i + s + 4) % 8]]
    const sc = [su[i % 8], su[(i + 5) % 8], sr[(i + 2) % 8], sr[(i + 7) % 8]]
    // slot：0＝劍正大正、1＝劍正大逆、2＝劍逆大正、3＝劍逆大逆
    const mg = MAJ_GOOD(m)
    const sg = SW_GOOD[sword]
    const majGood = [mg[0], mg[1], mg[0], mg[1]]
    const swGood = [sg[0], sg[0], sg[1], sg[1]]
    return [m, op.map((o, k) => {
      const key = (majGood[k] ? 'G' : 'B') + (swGood[k] ? 'G' : 'B')
      const c = CONN[key][(i + s + k) % 4]
      return `${o}，${c}${sc[k]}。`
    })]
  })
}
