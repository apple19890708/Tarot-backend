async function main() {
  await mongoose.connect(process.env.MONGO_URI, { dbName: process.env.MONGO_DB_NAME || 'tarot-divination' })

  const cards = await Card.find({ arcanaType: 'major' }).lean()
  const byName = new Map(cards.map((card) => [card.nameZh, card]))
  const orientations = [
    ['upright', 'upright'],
    ['upright', 'reversed'],
    ['reversed', 'upright'],
    ['reversed', 'reversed'],
  ]

  const ops = []
  const problems = []

  for (const [fromName, toName, texts] of ENTRIES) {
    const fromCard = byName.get(fromName)
    const toCard = byName.get(toName)
    if (!fromCard || !toCard) {
      problems.push(`找不到牌：${fromName} 或 ${toName}`)
      continue
    }
    if (texts.length !== 4) {
      problems.push(`${fromName}→${toName} 需要 4 段文字`)
      continue
    }

    orientations.forEach(([fromOrientation, toOrientation], i) => {
      const relation = analyzeCombination({
        entries: [
          { card: fromCard, orientation: fromOrientation },
          { card: toCard, orientation: toOrientation },
        ],
      }).pairs[0].relation

      ops.push({
        updateOne: {
          filter: { key: `${fromCard.slug}|${fromOrientation}>${toCard.slug}|${toOrientation}`, domain: DOMAIN },
          update: {
            $set: {
              key: `${fromCard.slug}|${fromOrientation}>${toCard.slug}|${toOrientation}`,
              fromSlug: fromCard.slug,
              fromOrientation,
              toSlug: toCard.slug,
              toOrientation,
              domain: DOMAIN,
              text: texts[i],
              relation,
              source: 'curated',
              model: '',
              reviewed: true,
            },
          },
          upsert: true,
        },
      })
    })
  }

  if (problems.length > 0) {
    problems.forEach((p) => console.error(p))
    throw new Error('資料有問題，未寫入')
  }

  const result = await CardPair.bulkWrite(ops)
  console.log(`寫入 ${ops.length} 筆（新增 ${result.upsertedCount}，更新 ${result.modifiedCount}）`)

  const total = await CardPair.countDocuments({ domain: DOMAIN })
  console.log(`工作領域目前共 ${total} / 1848 筆`)

  await mongoose.disconnect()
}

main().catch((error) => {
  console.error(error.message)
  process.exit(1)
})
