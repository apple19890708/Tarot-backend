const ORIENTATION_PAIRS = [
  ['upright', 'upright'],
  ['upright', 'reversed'],
  ['reversed', 'upright'],
  ['reversed', 'reversed'],
]

const entries = []
for (const [fromName, toName, texts] of COMBOS) {
  const fromSlug = S[fromName]
  const toSlug = S[toName]
  if (!fromSlug || !toSlug) {
    throw new Error(`找不到 slug：${fromName} 或 ${toName}`)
  }
  if (texts.length !== 4) {
    throw new Error(`${fromName}＋${toName} 需要 4 段文字，實際 ${texts.length}`)
  }
  ORIENTATION_PAIRS.forEach(([fromOrientation, toOrientation], i) => {
    entries.push({
      key: `${fromSlug}|${fromOrientation}>${toSlug}|${toOrientation}`,
      domain: 'any',
      fromName,
      toName,
      fromOrientation,
      toOrientation,
      text: texts[i],
    })
  })
}

