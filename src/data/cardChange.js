function normalizeNameEn(nameEn) {
  return String(nameEn || '')
    .toLowerCase()
    .replace(/^the\s+/, '')
    .replace(/[^a-z]/g, '')
}

// 回傳這張牌在這個正逆位的變動值；查不到回傳 null（不計入，並讓答案的把握降低）
function getChangeValue(card, profile, orientation) {
  let pair = null
  if (profile.kind === 'major') {
    pair = MAJOR_CHANGE[normalizeNameEn(card.nameEn)] || MAJOR_CHANGE[MAJOR_ZH_TO_KEY[String(card.nameZh || '').trim()]] || null
  } else if (profile.kind === 'court') {
    pair = COURT_CHANGE[profile.suit]?.[profile.courtRank] || null
  } else {
    pair = PIP_CHANGE[profile.suit]?.[profile.pipNumber] || null
  }
  if (!pair) return null
  return orientation === 'reversed' ? pair[1] : pair[0]
}

