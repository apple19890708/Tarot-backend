const test = require('node:test')
const assert = require('node:assert/strict')

const { digestMaterialNews } = require('../src/services/market/materialDigest')

// 2026-11-06 台達電的公告（節錄），「不適用」「無」「否」與估價、審議欄位都要拿掉
const CONTRACT = [
  '1.契約種類:工程合約',
  '2.事實發生日:115/11/6~115/11/6',
  '3.董事會通過日期: 民國115年4月29日',
  '4.其他核決日期: 不適用',
  '5.契約相對人及其與公司之關係:',
  '本案土建工程契約相對人為利晉工程股份有限公司(以下簡稱利晉)。',
  '利晉非本公司之關係人。',
  '6.契約主要內容（含契約總金額、預計參與投入之金額及契約起迄日期）',
  '、限制條款及其他重要約定事項:',
  '本公司董事會於民國115年4月29日決議通過興建觀音廠，暫估工程總價款約新台幣103億元。',
  '7.專業估價者事務所或公司名稱及其估價結果:',
  '係自地委建，故不適用。',
  '8.不動產估價師姓名:',
  '不適用',
  '10.取得之具體目的:',
  '因應未來業務發展所需',
  '11.本次交易表示異議之董事之意見:',
  '無',
  '12.本次交易為關係人交易:否',
  '13.監察人承認或審計委員會同意日期:',
  '民國115年4月29日',
].join('\n')

test('重大訊息重點：去掉空值、估價與審議欄位，括號補充與代稱拿掉', () => {
  const points = digestMaterialNews(CONTRACT)
  assert.deepEqual(
    points.map((p) => p.label),
    ['契約種類', '事實發生日', '契約相對人及其與公司之關係', '契約主要內容', '取得之具體目的'],
  )
  assert.equal(points[2].value, '本案土建工程契約相對人為利晉工程股份有限公司。 利晉非本公司之關係人。')
  assert.ok(points[3].value.includes('103億元'))
})

test('重大訊息重點：財報欄位改白話、保留單位、括號虧損改成負號，優先挑獲利欄位', () => {
  const detail = [
    '1.提報董事會或經董事會決議日期:115/11/06',
    '2.審計委員會通過日期:115/11/06',
    '3.財務報告或年度自結財務資訊報導期間起訖日期(XXX/XX/XX~XXX/XX/XX):115/01/01~115/09/30',
    '4.1月1日累計至本期止營業收入(仟元):324,075',
    '5.1月1日累計至本期止營業毛利(毛損) (仟元):56,306',
    '6.1月1日累計至本期止營業利益(損失) (仟元):(40,959)',
    '7.1月1日累計至本期止稅前淨利(淨損) (仟元):(30,379)',
    '8.1月1日累計至本期止本期淨利(淨損) (仟元):(25,669)',
    '9.1月1日累計至本期止歸屬於母公司業主淨利(損) (仟元):(25,669)',
    '10.1月1日累計至本期止基本每股盈餘(損失) (元):(0.54)',
    '11.期末總資產(仟元):1,000,000',
    '12.其他應敘明事項:無',
  ].join('\n')
  assert.deepEqual(digestMaterialNews(detail), [
    { label: '今年累計營業收入', value: '324,075 千元' },
    { label: '今年累計營業毛利', value: '56,306 千元' },
    { label: '今年累計營業利益', value: '-40,959 千元' },
    { label: '今年累計稅前淨利', value: '-30,379 千元' },
    { label: '今年累計淨利', value: '-25,669 千元' },
    { label: '今年累計每股盈餘', value: '-0.54 元' },
  ])
})

test('重大訊息重點：制式的「依規定辦理公告」與「本公司」當作沒有內容；不是編號格式時回傳空陣列', () => {
  const detail = ['1.事實發生日:115/11/06', '2.與公司關係:本公司', '3.發生緣由:依據「發行人募集與發行有價證券處理準則」規定辦理公告。'].join('\n')
  assert.deepEqual(digestMaterialNews(detail), [{ label: '事實發生日', value: '115/11/06' }])
  assert.deepEqual(digestMaterialNews('本公司今日召開法說會，簡報已上傳。'), [])
})

test('重大訊息原文欄位表：有內容的照原文列出，不適用／無／否的欄位名稱另外列', () => {
  const { materialFields } = require('../src/services/market/materialDigest')
  const { fields, empty } = materialFields(CONTRACT)
  assert.deepEqual(fields.map((f) => f.label).slice(0, 3), ['契約種類', '事實發生日', '董事會通過日期'])
  assert.equal(fields[3].value, '本案土建工程契約相對人為利晉工程股份有限公司(以下簡稱利晉)。\n利晉非本公司之關係人。')
  assert.ok(empty.includes('其他核決日期'))
  assert.ok(empty.includes('本次交易為關係人交易'))
  assert.ok(!fields.some((f) => f.value === '不適用'))
})
